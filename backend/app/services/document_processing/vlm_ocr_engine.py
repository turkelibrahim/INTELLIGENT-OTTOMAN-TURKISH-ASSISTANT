import base64
import json
import logging
import time
import cv2
import numpy as np
import requests
from typing import Dict, List, Tuple
from app.core.config import settings
from app.services.document_processing.ocr_engine import OCRLineResult, OCRPageResult

logger = logging.getLogger(__name__)

class VLMOCREngine:
    """
    Vision Language Model (VLM) OCR Engine.
    Uses OpenAI Vision API (or compatible APIs like Gemini via OpenAI compatible endpoints)
    to perform accurate OCR on Ottoman Turkish manuscripts.
    """

    def __init__(self, api_key: str, model_name: str = "gemini-1.5-flash"):
        self.api_key = api_key
        self.model_name = model_name
        self.engine_version = "vlm-ocr-v2"
        self.base_url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model_name}:generateContent?key={self.api_key}"

    def model_metadata(self) -> Dict:
        return {
            "name": "vlm_ocr_engine",
            "version": self.engine_version,
            "provider": "Google Gemini API",
            "model": self.model_name
        }

    async def extract(self, image: np.ndarray) -> OCRPageResult:
        """
        Extracts Ottoman Turkish text from the image using VLM.
        """
        start_time = time.time()
        
        # 1. Encode image to base64
        _, buffer = cv2.imencode(".jpg", image)
        base64_image = base64.b64encode(buffer).decode("utf-8")
        
        # 2. Prepare payload
        headers = {
            "Content-Type": "application/json"
        }
        
        system_prompt = (
            "Sen uzman bir belge okuma (OCR) ve paleografi uzmanısın. Verilen resimdeki el yazması veya matbu metni olduğu gibi, tam olarak okuman gerekiyor.\n"
            "ÇOK ÖNEMLİ KURALLAR:\n"
            "1. Resimdeki metin HANGİ ALFABEYLE (Arap harfleri, Latin harfleri, Kiril vb.) yazılmışsa, çıktıyı O ALFABEYLE ver.\n"
            "2. Eğer metin Osmanlıca (Arap harfli) ise Arap harfleri kullan, ancak kesinlikle modern Türkçe çeviri veya Latin harfli transkripsiyon UYDURMA.\n"
            "3. Eğer okuyamadığın, silik veya belirsiz bir kelime/harf varsa, oraya uydurmak yerine kesinlikle '[?]' veya '[okunamadı]' yaz.\n"
            "4. Sayfanın kenarlarındaki derkenar ve çıkmaları da dikkatle incele.\n"
            "5. Ana metni resimde gördüğün sıraya göre satır satır yaz. Satır sonlarında 'Enter' kullanarak fiziksel yapıyı koru.\n"
            "6. Kesinlikle hiçbir kelimeyi veya satırı atlama, olmayan bir kelimeyi de ekleme."
        )
        
        payload = {
            "system_instruction": {
                "parts": {
                    "text": system_prompt
                }
            },
            "contents": [
                {
                    "parts": [
                        {
                            "inline_data": {
                                "mime_type": "image/jpeg",
                                "data": base64_image
                            }
                        }
                    ]
                }
            ],
            "generationConfig": {
                "temperature": 0.1,
                "maxOutputTokens": 1500
            }
        }
        
        # 3. Call API
        try:
            # We use sync requests here for simplicity; since it's a backend worker it's generally fine,
            # or it can be run in a thread pool.
            response = requests.post(self.base_url, headers=headers, json=payload, timeout=120)
            response.raise_for_status()
            data = response.json()
            
            raw_text = data["candidates"][0]["content"]["parts"][0]["text"]
            lines_text = [line.strip() for line in raw_text.split("\n") if line.strip()]
            
            # 4. Generate dummy bounding boxes for lines (UI needs this)
            img_height, img_width = image.shape[:2]
            line_height = img_height // (len(lines_text) if len(lines_text) > 0 else 1)
            
            ocr_lines = []
            for i, text in enumerate(lines_text):
                # Fake bounding box: full width, incremental height
                bbox = (0, i * line_height, img_width, line_height)
                
                ocr_line = OCRLineResult(
                    text=text,
                    confidence=0.99,  # High confidence as it is generated by VLM
                    bbox=bbox,
                    line_index=i,
                    engine_name="vlm_ocr",
                    engine_version=self.engine_version,
                    device="cloud",
                    processing_time_ms=0.0
                )
                ocr_lines.append(ocr_line)
                
            elapsed_ms = (time.time() - start_time) * 1000
            
            # Simple hash for image
            import hashlib
            image_hash = hashlib.md5(image.tobytes()).hexdigest()
            
            return OCRPageResult(
                lines=ocr_lines,
                engine_name="vlm_ocr",
                engine_version=self.engine_version,
                device="cloud",
                page_confidence=0.99 if ocr_lines else 0.0,
                processing_time_ms=elapsed_ms,
                image_hash=image_hash,
                image_width=img_width,
                image_height=img_height,
                model_metadata=self.model_metadata()
            )
            
        except Exception as e:
            logger.error(f"VLM OCR Engine failed: {e}")
            if hasattr(e, 'response') and e.response is not None:
                logger.error(f"Response data: {e.response.text}")
            raise RuntimeError(f"VLM API Call Failed: {str(e)}")
